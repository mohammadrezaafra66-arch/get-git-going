-- Migration 214 — رفع دائمی خرابی encoding «زمان تسویه» (payment_terms)
--
-- زمینه (طبق docs/research/settlement-encoding-diagnosis.md):
--   seed اصلی در migration 20260506164214 پنج نوع تسویه را با فارسیِ درست درج می‌کرد،
--   ولی هنگام اجرا روی یک کانال تک‌بایتی (PowerShell/psql بدون UTF-8) هر بایتِ غیر-ASCII
--   به کاراکتر «?» تبدیل شد. نتیجه:
--     ۱) نام هر سه ردیف بازمانده به `????` تبدیل شد.
--     ۲) «۳۰ روزه»/«۶۰ روزه»/«۹۰ روزه» همه به یک رشتهٔ یکسان `???? ????????` رسیدند و
--        چون جدول `UNIQUE (name)` دارد و seed از `ON CONFLICT (name) DO NOTHING`
--        استفاده می‌کرد، دو ردیف (days=60 و days=90) **بی‌صدا دور انداخته شدند**.
--
-- چرا این migration ریشه را حل می‌کند:
--   همگام‌سازی بر پایهٔ `days` (عدد صحیح، مصون از خرابی encoding) انجام می‌شود، نه بر
--   پایهٔ `name` (رشتهٔ فارسیِ نمایشی که خودش قربانی خرابی شد). پس این migration یک گام
--   «خودترمیم» است: در هر بازسازی آینده، حتی اگر seed قدیمی دوباره خراب اجرا شود، این
--   migration بعد از آن اجرا می‌شود و هر پنج ردیف را به مقدار درست می‌رساند.
--
-- idempotent: اگر داده از قبل درست باشد (مثلاً بخش A دستی انجام شده باشد)، هیچ ردیفی
--   تغییر نمی‌کند و هیچ ردیف تکراری ساخته نمی‌شود.
--
-- روش اجرای امن (حیاتی): این فایل باید با `docker cp` به کانتینر منتقل و با `psql -f`
--   اجرا شود. هرگز محتوای فارسی را از طریق pipe در PowerShell به psql نفرستید — همان
--   کانال، عامل اصلی این خرابی بود.

SET client_encoding = 'UTF8';

BEGIN;

-- ---------------------------------------------------------------------------
-- ۱) ترمیم ردیف‌های موجود — کلید تطبیق: `days`
--    فقط `name` و `sort_order` (همان دو چیزی که در مشخصات هدف تعریف شده‌اند) اصلاح
--    می‌شوند. `is_active` عمداً دست‌کاری نمی‌شود تا اگر مدیری آگاهانه یک نوع تسویه را
--    غیرفعال کرده باشد، این migration آن را بی‌اجازه دوباره فعال نکند.
--    شرط IS DISTINCT FROM باعث می‌شود اجرای دوباره هیچ ردیفی را لمس نکند (idempotent).
-- ---------------------------------------------------------------------------
UPDATE public.payment_terms AS pt
   SET name       = t.name,
       sort_order = t.sort_order,
       updated_at = now()
  FROM (VALUES
    (0,  1, 'نقدی'),
    (30, 2, 'تسویه ۳۰ روزه'),
    (60, 3, 'تسویه ۶۰ روزه'),
    (90, 4, 'تسویه ۹۰ روزه'),
    (45, 5, 'چک ۴۵ روزه')
  ) AS t(days, sort_order, name)
 WHERE pt.days = t.days
   AND (pt.name       IS DISTINCT FROM t.name
     OR pt.sort_order IS DISTINCT FROM t.sort_order);

-- ---------------------------------------------------------------------------
-- ۲) بازساخت ردیف‌های گم‌شده — همان دو ردیفی که خرابی encoding حذفشان کرد
--    (days=60 و days=90). تطبیق وجود، بر پایهٔ `days` است نه `name`.
--    نام‌های درست همه با هم یکتا هستند، پس قید `UNIQUE (name)` مشکلی ایجاد نمی‌کند.
-- ---------------------------------------------------------------------------
INSERT INTO public.payment_terms (name, days, sort_order, is_active)
SELECT t.name, t.days, t.sort_order, true
  FROM (VALUES
    (0,  1, 'نقدی'),
    (30, 2, 'تسویه ۳۰ روزه'),
    (60, 3, 'تسویه ۶۰ روزه'),
    (90, 4, 'تسویه ۹۰ روزه'),
    (45, 5, 'چک ۴۵ روزه')
  ) AS t(days, sort_order, name)
 WHERE NOT EXISTS (
   SELECT 1 FROM public.payment_terms p WHERE p.days = t.days
 );

COMMIT;

-- ---------------------------------------------------------------------------
-- یادداشت دربارهٔ قید یکتای `days` (بررسی شد و عمداً اضافه نشد):
--   بریف اصلاح، افزودن `UNIQUE (days)` را به‌عنوان گزینهٔ اختیاری «محکم‌تر» مطرح کرد.
--   پیش‌شرطش تأیید شد (۰ مقدار تکراری، ۰ مقدار NULL)، ولی اضافه نشد چون:
--     ۱) ستون `days` nullable است و در PostgreSQL مقادیر NULL از نظر UNIQUE متمایزند،
--        پس این قید در عمل جلوی چند ردیفِ days تهی را نمی‌گیرد (تضمین ناقص).
--     ۲) همین مجموعهٔ هدف، «ابزار پرداخت» را در طول‌مدت یکسان تفکیک می‌کند
--        («چک ۴۵ روزه» در برابر «تسویه N روزه»). یک نیاز کاملاً معقول در آینده مثل
--        «چک ۳۰ روزه» در کنار «تسویه ۳۰ روزه» با UNIQUE(days) مسدود می‌شد.
--   ریشهٔ مشکل با همگام‌سازی بر پایهٔ `days` در همین migration رفع شده و نام‌های درست
--   ذاتاً یکتا هستند؛ پس افزودن قید ساختاری لازم نیست.
