# واژه‌نامه

- **XP (Experience Points)**: امتیاز تجربه که با انجام فعالیت‌های معتبر کسب می‌شود.
- **Level**: سطح کلی کاربر بر مبنای مجموع XP.
- **League**: لیگ فصلی (Bronze تا Legend).
- **Season**: بازهٔ زمانی یک فصل گیمیفیکیشن.
- **KPI Rule**: قانون امتیازدهی که می‌گوید هر event_key چقدر XP می‌دهد.
- **Event Key**: شناسهٔ یکتای یک رویداد قابل امتیازدهی، مثل `outbound_call`.
- **Achievement**: مدال؛ با تحقق یک شرط آزاد و دائمی است.
- **Mission**: مأموریت با مهلت زمانی (روزانه/هفتگی/ماهانه/سفارشی).
- **Reward**: پاداش قابل تخصیص به کاربران موفق فصل.
- **Leaderboard**: جدول رتبه‌بندی فصلی.
- **Audit Log**: گزارش تغییرات حساس کاربران در سیستم.
- **RBAC (Role-Based Access Control)**: کنترل دسترسی بر اساس نقش کاربر.
- **RLS (Row-Level Security)**: امنیت سطر، یعنی هر کاربر فقط ردیف‌هایی را می‌بیند که اجازهٔ آن‌ها را دارد.

