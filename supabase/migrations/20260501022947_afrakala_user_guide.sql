# شروع سریع

## ۱. ورود به سیستم
1. آدرس سامانه را در مرورگر باز کنید.
2. ایمیل و رمز عبور خود را وارد کنید و روی «ورود» بزنید.
3. اگر حساب شما تأیید نشده باشد، پیام «در انتظار تأیید» نمایش داده می‌شود؛ با ادمین تماس بگیرید.

## ۲. آشنایی با داشبورد
- داشبورد، صفحهٔ اصلی پس از ورود است.
- خلاصه‌ای از وضعیت کاری شما، بسته به نقش، نمایش داده می‌شود.

## ۳. منوی سمت راست (Sidebar)
منو به این گروه‌ها تقسیم شده است:
1. اصلی → داشبورد
2. فروش و CRM → مشتریان، پیش‌فاکتورها، فاکتورها، اعتبارسنجی
3. قیمت‌گذاری → لیست قیمت زنده، کارگاه قیمت، تابلوی امین حضور
4. عملیات → محصولات، خرید، تأمین‌کنندگان، حال‌وهوای امروز
5. مالی → فیش‌های واریزی، گزارش‌ها
6. گیمیفیکیشن → داشبورد گیمیفیکیشن، لیدربورد
7. مدیریت گیمیفیکیشن (فقط ادمین/مدیر)
8. ارتباطات → دانش سازمانی، آکادمی، پیام‌ها
9. مدیریت سیستم (فقط ادمین)

## ۴. نقش‌های کاربری
- **admin**: دسترسی کامل به همهٔ بخش‌ها و تنظیمات.
- **manager**: مدیریت تیم، گزارش‌ها، گیمیفیکیشن.
- **sales**: کار روزمرهٔ فروش، مشتریان، پیش‌فاکتور، گیمیفیکیشن شخصی.
- **accountant**: بخش‌های مالی، فاکتور، قیمت‌گذاری.
- **viewer**: فقط مشاهدهٔ گزارش‌ها و داده‌ها بدون امکان تغییر.

