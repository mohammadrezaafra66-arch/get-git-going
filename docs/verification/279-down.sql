# لیگ‌ها، فصل‌ها و پاداش‌ها

## ۱. لیگ‌ها
- ترتیب: Bronze → Silver → Gold → Platinum → Diamond → Master → Legend.
- هر کاربر در ابتدای فصل بر اساس عملکرد گذشته در یکی از لیگ‌ها قرار می‌گیرد.

## ۲. Season (فصل)
- هر فصل بازهٔ زمانی مشخص دارد (مثلاً ماهانه یا سه‌ماهه).
- در پایان فصل، رتبه‌بندی محاسبه و آماده‌سازی فصل بعد انجام می‌شود.

## ۳. درصد ارتقا و سقوط
- درصدی از بالای جدول هر لیگ به لیگ بالاتر ارتقا می‌یابند.
- درصدی از پایین به لیگ پایین‌تر سقوط می‌کنند.
- مقادیر دقیق در صفحهٔ مدیریت لیگ‌ها قابل تنظیم است.

## ۴. Preview ارتقا/سقوط
- در `/gamification/admin/leagues` می‌توانید پیش‌نمایش ارتقا/سقوط فصل جاری را ببینید.

## ۵. ⚠️ محدودیت
**اعمال خودکار ارتقا/سقوط لیگ هنوز پیاده‌سازی نشده است.** فعلاً فقط preview در دسترس است و اعمال نهایی باید دستی انجام شود.

