- **Mission** مهلت زمانی دارد و در پایان دوره می‌سوزد یا تمدید می‌شود.
- **Achievement** یک‌بار آزاد می‌شود و دائمی است.

## ۶. انواع مأموریت
- روزانه: مثل «۵ تماس خروجی امروز».
- هفتگی: مثل «۳ مشتری جدید این هفته».
- ماهانه: مثل «۱۰ فروش بسته‌شده این ماه».
