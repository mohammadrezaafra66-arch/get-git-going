# مدال‌ها (Achievements) و مأموریت‌ها (Missions)

## ۱. ساخت Achievement
1. مسیر: `/gamification/admin/achievements`
2. روی «افزودن» بزنید.
3. عنوان، توضیح، شرط (مثلاً «۱۰ فروش بسته‌شده») و XP جایزه را وارد کنید.

## ۲. شرط Achievement
- معمولاً به‌صورت آستانه روی یک event_key تعریف می‌شود.
- مثال: `sale_closed >= 10`

## ۳. XP جایزه
- مقدار XPی که هنگام آزاد شدن مدال به کاربر اضافه می‌شود.

## ۴. ساخت Mission
1. مسیر: `/gamification/admin/missions`
