# سؤالات پرتکرار (FAQ)

## ۱. چرا یک صفحه برای من باز نمی‌شود؟
نقش شما اجازهٔ مشاهدهٔ آن صفحه را ندارد. با ادمین برای بررسی نقش خود تماس بگیرید.

## ۲. چرا به /unauthorized می‌روم؟
این یعنی RBAC اجازهٔ ورود به آن مسیر را به نقش شما نداده است.

## ۳. چرا امتیازم تغییر نکرد؟
- ممکن است قانون مربوطه غیرفعال باشد.
- ممکن است رویداد ثبت نشده باشد.
- چند ثانیه صبر و سپس صفحه را تازه کنید.

## ۴. چرا مدال آزاد نشد؟
- ممکن است هنوز شرط مدال کامل نشده باشد.
- بعضی مدال‌ها در دوره‌های مشخص بازبینی می‌شوند.

## ۵. چرا مأموریت کامل نشده نمایش داده می‌شود؟
- شرط مأموریت کامل نیست.
- یا رویداد مرتبط در بازهٔ مأموریت ثبت نشده است.

## ۶. چرا لیگ من تغییر نکرد؟
**اعمال خودکار ارتقا/سقوط لیگ هنوز پیاده‌سازی نشده است.** تغییر لیگ فعلاً دستی انجام می‌شود.

## ۷. چرا پاداش خودکار اعمال نشده؟
**اجرای خودکار پاداش‌ها هنوز پیاده‌سازی نشده است.**

## ۸. چرا نرخ دلار یا اطلاعات قیمت‌گذاری را نمی‌بینم؟
این اطلاعات بر اساس نقش محدود می‌شوند. نقش viewer یا sales ممکن است دسترسی کامل به نرخ داخلی نداشته باشد.
